"""Extract line-level permissions from the exact published CEL edition, without executing it.

Usage: python3 freeze_permissions.py path/to/cel-gh-pages > permissions.toml
The input repository must contain the pinned deployment. Reads only committed files.
"""
from hashlib import sha256
from html.parser import HTMLParser
from pathlib import Path
import json
import subprocess
import sys

DEPLOY = "967294b5d47e077a5208a5dece56bd3bb29d37db"
EDITION = "88250e0392cef0622f318e35469108d68694c1f7"
NAMES = (("read", "read"), ("write", "write"), ("drop", "own"))


def describe(state):
    changes = []
    for place, details in state:
        permissions = details["permissions"]
        for direction, verb in (("High", "gains"), ("Low", "loses")):
            names = [label for key, label in NAMES if permissions[key]["type"] == direction]
            if names:
                changes.append(f"`{place}` {verb} {' and '.join(names)}.")
    return " ".join(changes)


class Examples(HTMLParser):
    def __init__(self):
        super().__init__()
        self.entries = {}

    def handle_starttag(self, tag, fields):
        attrs = dict(fields)
        if "data-operations" not in attrs:
            return
        if "stepper" not in json.loads(attrs["data-config"]):
            return
        code = json.loads(attrs["data-code"]).splitlines()
        annotations = json.loads(attrs["data-annotations"])
        hidden = set(annotations["hidden_lines"])
        visible = {n: line for n, line in enumerate(code, 1) if n not in hidden}
        source = "\n".join(visible.values())
        rows = []
        for body in json.loads(attrs["data-responses"]).get("permissions", []):
            for step in body.get("Ok", {}).get("steps", []):
                line = step["location"]["start"]["line"] + 1
                if line not in visible:
                    continue
                branches = step["state"]
                texts = []
                for branch in branches:
                    message = describe(branch["state"])
                    if message and len(branches) > 1:
                        predecessor = branch["from"]["start"]["line"] + 1
                        if predecessor in visible:
                            predecessor = list(visible).index(predecessor) + 1
                            message = f"From line {predecessor}: {message}"
                        else:
                            message = f"From a hidden line: {message}"
                    if message and message not in texts:
                        texts.append(message)
                if texts:
                    position = step["location"]["start"]
                    rows.append((line, position["column"], "\n\n".join(texts)))
        if not rows:
            return
        steps = [(f"Line {list(visible).index(line) + 1} · {code[line-1].strip()}", text)
                 for line, _, text in sorted(rows)]
        key = sha256(source.encode()).hexdigest()
        if key in self.entries and self.entries[key] != steps:
            raise ValueError("same visible source has two different traces")
        self.entries[key] = steps


def main(repo):
    def git(*args):
        return subprocess.check_output(["git", "-C", repo, *args]).decode()
    assert git("show", "-s", "--format=%s", DEPLOY).strip() == f"deploy: {EDITION}"
    print(f"# Generated by freeze_permissions.py from CEL deployment {DEPLOY}")
    paths = git("ls-tree", "--name-only", DEPLOY).splitlines()
    for path in sorted(p for p in paths if p.endswith(".html") and (p.startswith("ch") or p == "experiment-intro.html")):
        parser = Examples()
        parser.feed(git("show", f"{DEPLOY}:{path}"))
        for digest, steps in sorted(parser.entries.items()):
            print(f'\n["src/{Path(path).stem}.md".{digest}]')
            print("steps = [")
            for row in steps:
                print("  " + json.dumps(row, ensure_ascii=False) + ",")
            print("]")


if __name__ == "__main__":
    main(sys.argv[1])
